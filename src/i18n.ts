export const copy: Record<Lang, Copy> = { en, es, ht }

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => values[key] ?? "")
}

export function formatPassDate(date: Date, lang: Lang): string {
  const locale = lang === "es" ? "es-US" : lang === "ht" ? "ht" : "en-US"
  return new Intl.DateTimeFormat(locale, {
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(date)
}
